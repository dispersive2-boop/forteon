# -*- coding: utf-8 -*-
"""Классификация предложений заметки: что сделано, что надо, что ждём.

Зачем отдельный модуль. Раньше извлечение задач опиралось на список слов
(«нужно», «надо», «необходимо»). Из-за этого:

  * «Отправил КП» — уже выполнено, но создавалась задача «Отправил КП»;
  * «Согласовали договор» — тоже выполнено, снова задача;
  * «Ждём ответ от бухгалтерии» — это ожидание, а не действие менеджера,
    но задача создавалась без пометки, кто кому должен;
  * «Позвоню в пятницу» — без слова «надо» действие не распознавалось;
  * отсутствие даты отправляло задачу в «Уточнить», хотя действие ясное.

Здесь цель — определить ТИП события. Тип решает, создавать ли задачу и
какую, а срок определяется отдельно (dates.py). Отсутствие даты больше не
блокирует создание задачи.

Типы:
  DONE     — уже выполнено. Задача не создаётся, факт идёт в историю.
  TODO     — необходимо сделать (нам). Задача создаётся.
  WAITING  — ожидаем от клиента/третьей стороны. Создаётся задача контроля.
  FACT     — просто информация. Ничего не создаётся.
  UNCLEAR  — действие вроде есть, но непонятно чьё/какое. Идёт на уточнение.
"""
from __future__ import annotations

import re
from dataclasses import dataclass


DONE = "done"
TODO = "todo"
WAITING = "waiting"
FACT = "fact"
UNCLEAR = "unclear"

# Глаголы прошедшего времени и свёрнутые формы: действие уже случилось.
# Список сознательно широкий, но только по корням, которые однозначны.
_DONE_ROOTS = (
    "отправил", "отправила", "отправили", "выслал", "выслали", "направил", "направили",
    "позвонил", "позвонила", "позвонили", "созвонил", "созвонил", "набрал", "набрали",
    "написал", "написала", "написали", "ответил", "ответили",
    "согласовал", "согласовали", "согласовано", "подписал", "подписали", "подписано",
    "обсудил", "обсудили", "обсуждено", "переговорил", "переговорили",
    "сделал", "сделали", "сделано", "подготовил", "подготовили", "подготовлено",
    "проверил", "проверили", "проверено", "выяснил", "выяснили", "уточнил", "уточнили",
    "сформировал", "сформировали", "передал", "передали", "передано",
    "заключил", "заключили", "заключён", "заключен",
    "оплатил", "оплатили", "оплачено", "перевёл", "перевели",
    "встретился", "встретились", "провёл", "провели", "проведено",
    "загрузил", "загрузили", "загружено", "зарегистрировал", "зарегистрировали",
    "смонтировал", "смонтировали", "установил", "установили", "установлено",
    "настроил", "настроили", "настроено", "запустил", "запустили", "запущено",
)

# «Уже», «готово» — усилители завершённости, но сами по себе не решают.
_DONE_MARKERS = ("уже ", "готово", "выполнено", "закрыт", "закрыли", "закрыто")

# Ожидание от другой стороны.
_WAITING_ROOTS = (
    "ждём", "ждем", "ожидаем", "ожидает", "ждать",
    "обещал", "обещали", "обещает", "пообещал",
    "попросили", "просили", "запросили", "запросил",
    "должны", "должен", "должно", "обязуется",
    "на стороне", "со стороны клиента", "от них", "от клиента",
    "не ответили", "нет ответа", "нет решения", "не прислали", "не предоставили",
    "на согласовании", "на рассмотрении", "на проверке у",
)

# Явное намерение сделать (наше действие).
_TODO_ROOTS = (
    "надо", "нужно", "необходимо", "следует", "требуется",
    "подготов", "позвон", "отправ", "напис", "подпис", "согласова",
    "оплат", "встрет", "сдела", "провер", "выясн", "уточн",
    "запрос", "напомн", "сформир", "переда", "выстав", "заказ",
    "связ", "обсуд", "согласу", "запроси", "собер", "рассчит",
    "загруз", "настро", "установ", "смонтир", "запус", "заключ",
)

# Будущее время первого лица: «позвоню», «отправлю», «сделаю» — это TODO,
# даже если нет слов «надо/нужно».
_FUTURE_1ST = re.compile(
    r"\b(позвоню|наберу|отправлю|напишу|подпишу|согласую|оплачу|встречусь|"
    r"сделаю|проверю|выясню|уточню|запрошу|напомню|сформирую|передам|"
    r"выставлю|свяжусь|обсужу|соберу|рассчитаю|загружу|настрою|установлю|"
    r"запущу|заключу|подготовлю|направлю|вышлю|перезвоню)\b",
    re.IGNORECASE,
)

# Повелительное наклонение / инфинитив в начале: «Отправить КП», «Позвонить».
_IMPERATIVE = re.compile(
    r"^\s*(?:-\s*)?(отправ|позвон|напис|подпис|соглас|оплат|встрет|сдел|провер|"
    r"выясн|уточн|запрос|напомн|сформир|переда|выстав|связ|обсуд|подготов|направ|"
    r"высл|перезвон|загруз|настро|установ|запус|заключ)",
    re.IGNORECASE,
)

# «Не надо», «не звонить» — отрицание, задача не создаётся.
_NEGATION = (
    "не надо", "не нужно", "не будем", "не звонить", "не отправлять",
    "не подписывать", "не платить", "отменил", "отменили", "отменяем",
    "не актуально", "отказ",
)

# Слова, после которых «должны» означает обязательство клиента, а не нам.
_THIRD_PARTY = (
    "клиент", "они", "заказчик", "бухгалтер", "директор", "подрядчик",
    "поставщик", "банк", "юрист", "финансовый", "снабжен",
)


@dataclass
class Event:
    """Результат классификации одного предложения."""
    kind: str                      # done | todo | waiting | fact | unclear
    sentence: str
    actor: str = "us"              # us | client
    due_hint: str | None = None    # фраза со сроком, если найдена (для dates.py)
    done_phrase: str | None = None  # что именно сделано (для истории)
    confidence: float = 0.5

    @property
    def creates_task(self) -> bool:
        return self.kind in (TODO, WAITING, UNCLEAR)

    @property
    def needs_review(self) -> bool:
        return self.kind == UNCLEAR


def _has(text: str, roots: tuple[str, ...]) -> str | None:
    """Возвращает первое совпавшее слово-корень или None."""
    for root in roots:
        if root in text:
            return root
    return None


def _is_negated(text: str) -> bool:
    return any(marker in text for marker in _NEGATION)


def _third_party(text: str) -> bool:
    return any(word in text for word in _THIRD_PARTY)


def classify(sentence: str) -> Event:
    """Определяет тип события по одному предложению.

    Порядок проверок важен:
      1. отрицание — сразу отказ от задачи;
      2. ожидание от клиента (в нём же «должны», если рядом третья сторона);
      3. уже выполнено;
      4. явное намерение сделать;
      5. иначе — факт или неясно.
    """
    text = (sentence or "").strip()
    low = text.lower()

    if not text:
        return Event(kind=FACT, sentence=text, confidence=0.9)

    if _is_negated(low):
        return Event(kind=FACT, sentence=text, confidence=0.8)

    # --- ожидание ---
    waiting_hit = _has(low, _WAITING_ROOTS)
    if waiting_hit:
        actor = "client" if (_third_party(low) or waiting_hit in
                             ("ждём", "ждем", "ожидаем", "обещал", "обещали", "обещает",
                              "попросили", "просили", "запросили", "запросил")) else "us"
        return Event(kind=WAITING, sentence=text, actor=actor, confidence=0.8)

    # «должны» без третьей стороны — это наше обязательство
    if "должны" in low or "должен" in low:
        if _third_party(low):
            return Event(kind=WAITING, sentence=text, actor="client", confidence=0.7)
        return Event(kind=TODO, sentence=text, actor="us", confidence=0.6)

    # --- уже выполнено ---
    done_hit = _has(low, _DONE_ROOTS)
    done_marker = _has(low, _DONE_MARKERS)
    if done_hit or done_marker:
        # «Отправил КП» → DONE. Но «надо отправить» сюда не попадает: там
        # явное намерение, а не прошедшее время.
        #
        # _IMPERATIVE здесь НЕ проверяем намеренно. Он сравнивает начало
        # слова с корнем («отправ»), поэтому ложно срабатывает на прошедшем
        # времени: «Отправил» начинается с «отправ», и проверка done
        # отменялась — задача создавалась на уже выполненное действие.
        # Инфинитивы («отправить», «согласовать») в _DONE_ROOTS не входят,
        # потому что там перечислены только формы прошедшего времени.
        future = bool(_FUTURE_1ST.search(text))
        todo_explicit = _has(low, ("надо", "нужно", "необходимо", "следует", "требуется"))
        if not future and not todo_explicit:
            return Event(
                kind=DONE,
                sentence=text,
                actor="us",
                done_phrase=text,
                confidence=0.85 if done_hit else 0.6,
            )

    # --- намерение сделать ---
    todo_hit = _has(low, _TODO_ROOTS)
    if todo_hit:
        return Event(kind=TODO, sentence=text, actor="us", confidence=0.8)

    if _FUTURE_1ST.search(text):
        return Event(kind=TODO, sentence=text, actor="us", confidence=0.75)

    if _IMPERATIVE.match(text):
        return Event(kind=TODO, sentence=text, actor="us", confidence=0.7)

    # --- остальное ---
    # Предложение с глаголом действия, но без явного времени — неясно.
    if re.search(r"\b(?:переговор|созвон|встреч|договор|кп|счёт|счет)\w*", low):
        return Event(kind=UNCLEAR, sentence=text, confidence=0.4)

    return Event(kind=FACT, sentence=text, confidence=0.5)


def classify_body(body: str) -> list[Event]:
    """Классифицирует все предложения заметки."""
    from .ai import _sentences  # локальный импорт: ai импортирует events

    return [classify(s) for s in _sentences(body or "")]


def review_question(event: Event) -> str:
    """Конкретный вопрос менеджеру для неясного предложения (п.14).

    Нужен не «уточните», а понятное действие: что именно спросить.
    """
    text = event.sentence.lower()

    if event.kind == WAITING and not event.actor:
        return "Кто должен сделать: мы или клиент?"
    if event.kind == UNCLEAR:
        if any(w in text for w in ("переговор", "созвон", "позвон")):
            return "Это уже сделано или ещё нужно позвонить?"
        if any(w in text for w in ("договор", "кп", "счёт", "счет", "документ")):
            return "Документ уже отправлен или его ещё нужно подготовить?"
        if any(w in text for w in ("встреч", "совещан")):
            return "Встреча прошла или её нужно назначить?"
        return "Это уже сделано или это задача на будущее?"

    return "Уточните формулировку"
